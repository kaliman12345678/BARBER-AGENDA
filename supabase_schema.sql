-- 0. TABLA PRINCIPAL DE BARBERÍAS (TENANTS)
CREATE TABLE IF NOT EXISTS barberias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  nombre TEXT NOT NULL,
  eslogan TEXT,
  logo_url TEXT,
  color_primario TEXT DEFAULT '#2563eb',
  color_secundario TEXT DEFAULT '#1e293b',
  telefono TEXT,
  direccion TEXT,
  plan TEXT DEFAULT 'vip', -- 'basico', 'pro', 'vip'
  modulos_activos JSONB DEFAULT '{"agenda":true,"max_barberos":999,"portal_barberos":true,"liquidaciones":true,"costos":true,"notificaciones_audio":true,"productos":true,"rentabilidad":true,"galeria":true,"auditoria":true}'::jsonb,
  pin_admin TEXT DEFAULT '1234',
  activo INTEGER DEFAULT 1,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 1. TABLA DE CONFIGURACIÓN GLOBAL
CREATE TABLE IF NOT EXISTS configuracion (
  clave TEXT PRIMARY KEY,
  valor TEXT
);

-- 2. TABLA DE BARBEROS
CREATE TABLE IF NOT EXISTS barberos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  nombre TEXT NOT NULL,
  telefono TEXT,
  email TEXT UNIQUE,
  password TEXT DEFAULT '123456',
  pin TEXT DEFAULT '1234',
  foto_url TEXT,
  porcentaje_comision NUMERIC DEFAULT 50.0,
  horario_inicio TEXT DEFAULT '09:00',
  horario_fin TEXT DEFAULT '20:00',
  dias_laborales TEXT DEFAULT '1,2,3,4,5,6',
  activo INTEGER DEFAULT 1,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA DE SERVICIOS
CREATE TABLE IF NOT EXISTS servicios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  nombre TEXT NOT NULL,
  precio_cop BIGINT NOT NULL,
  duracion_minutos INTEGER NOT NULL DEFAULT 45,
  descripcion TEXT,
  activo INTEGER DEFAULT 1,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABLA DE BLOQUEOS DE HORARIO
CREATE TABLE IF NOT EXISTS bloqueos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  barbero_id BIGINT REFERENCES barberos(id) ON DELETE CASCADE,
  fecha TEXT NOT NULL,
  hora_inicio TEXT NOT NULL,
  hora_fin TEXT NOT NULL,
  motivo TEXT NOT NULL,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABLA DE LIQUIDACIONES / PAGOS A BARBEROS
CREATE TABLE IF NOT EXISTS liquidaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  barbero_id BIGINT NOT NULL REFERENCES barberos(id) ON DELETE RESTRICT,
  fecha_inicio TEXT NOT NULL,
  fecha_fin TEXT NOT NULL,
  total_servicios INTEGER NOT NULL,
  total_bruto BIGINT NOT NULL,
  porcentaje_aplicado NUMERIC NOT NULL,
  monto_comision BIGINT NOT NULL,
  deducciones BIGINT DEFAULT 0,
  total_pagado BIGINT NOT NULL,
  metodo_pago TEXT DEFAULT 'Efectivo',
  fecha_pago TIMESTAMPTZ DEFAULT NOW(),
  notas TEXT
);

-- 6. TABLA DE CITAS / TURNOS
CREATE TABLE IF NOT EXISTS citas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  barbero_id BIGINT NOT NULL REFERENCES barberos(id) ON DELETE RESTRICT,
  servicio_id BIGINT NOT NULL REFERENCES servicios(id) ON DELETE RESTRICT,
  cliente_nombre TEXT NOT NULL,
  cliente_telefono TEXT NOT NULL,
  fecha TEXT NOT NULL,
  hora_inicio TEXT NOT NULL,
  hora_fin TEXT NOT NULL,
  estado TEXT DEFAULT 'confirmada', -- confirmada, completada, cancelada, no_asistio
  precio_cobrado BIGINT NOT NULL,
  notas TEXT,
  liquidacion_id BIGINT REFERENCES liquidaciones(id) ON DELETE SET NULL,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 7. TABLA DE COSTOS / CAJA CHICA & EGRESOS
CREATE TABLE IF NOT EXISTS costos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  tipo TEXT DEFAULT 'egreso', -- egreso o ingreso
  categoria TEXT NOT NULL,
  descripcion TEXT NOT NULL,
  monto_cop BIGINT NOT NULL,
  fecha TEXT NOT NULL,
  metodo_pago TEXT DEFAULT 'Efectivo',
  barbero_id BIGINT REFERENCES barberos(id) ON DELETE SET NULL,
  notas TEXT,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 8. TABLA DE PRODUCTOS DE TIENDA
CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  nombre TEXT NOT NULL,
  foto_url TEXT,
  stock INTEGER NOT NULL DEFAULT 0,
  precio_venta BIGINT NOT NULL,
  costo_compra BIGINT NOT NULL DEFAULT 0,
  porcentaje_comision NUMERIC DEFAULT 10.0,
  categoria TEXT DEFAULT 'Cuidado Capilar',
  descripcion TEXT,
  activo INTEGER DEFAULT 1,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 9. TABLA DE VENTAS DE PRODUCTOS
CREATE TABLE IF NOT EXISTS ventas_productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  producto_id BIGINT NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
  cantidad INTEGER NOT NULL DEFAULT 1,
  precio_unitario BIGINT NOT NULL,
  costo_unitario BIGINT NOT NULL DEFAULT 0,
  total_venta BIGINT NOT NULL,
  porcentaje_comision NUMERIC NOT NULL,
  monto_comision BIGINT NOT NULL,
  ganancia_neta BIGINT NOT NULL,
  barbero_id BIGINT REFERENCES barberos(id) ON DELETE SET NULL,
  metodo_pago TEXT DEFAULT 'Efectivo',
  fecha TEXT NOT NULL,
  notas TEXT,
  liquidacion_id BIGINT REFERENCES liquidaciones(id) ON DELETE SET NULL,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

-- 10. TABLA DE AUDITORÍA TOTAL DE MOVIMIENTOS
CREATE TABLE IF NOT EXISTS auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  tipo_evento TEXT NOT NULL,
  descripcion TEXT NOT NULL,
  usuario TEXT DEFAULT 'admin',
  detalles_json TEXT,
  fecha_hora TIMESTAMPTZ DEFAULT NOW()
);

-- 11. TABLA DE GALERÍA MULTIMEDIA & REDES
CREATE TABLE IF NOT EXISTS galeria_multimedia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barberia_id BIGINT DEFAULT 1 REFERENCES barberias(id) ON DELETE CASCADE,
  titulo TEXT NOT NULL,
  tipo TEXT DEFAULT 'imagen',
  url_media TEXT NOT NULL,
  url_red_social TEXT,
  descripcion TEXT,
  barbero_id BIGINT REFERENCES barberos(id) ON DELETE SET NULL,
  orden INTEGER DEFAULT 0,
  activo INTEGER DEFAULT 1,
  creado_en TIMESTAMPTZ DEFAULT NOW()
);

